export const SUPPORTED_LOCALES = ['en', 'fr', 'id', 'ru', 'de', 'zh', 'ja', 'es'];

export function t(key, lang) {
  const l = SUPPORTED_LOCALES.includes(lang) ? lang : 'en';
  const entry = STRINGS[key];
  if (!entry) return key;
  return entry[l] ?? entry.en ?? key;
}

// Substitute {placeholder} tokens in a translated string.
// Only used where pluralisation / dynamic-N is needed.
export function tn(key, lang, vars = {}) {
  const raw = t(key, lang);
  return raw.replace(/\{(\w+)\}/g, (_, name) => (vars[name] != null ? String(vars[name]) : `{${name}}`));
}

function detectFromTelegram() {
  if (typeof window === 'undefined') return null;
  const tg = window.Telegram?.WebApp;
  const code = tg?.initDataUnsafe?.user?.language_code;
  if (typeof code !== 'string') return null;
  const two = code.slice(0, 2).toLowerCase();
  return SUPPORTED_LOCALES.includes(two) ? two : null;
}

function detectFromNavigator() {
  if (typeof navigator === 'undefined') return null;
  const code = navigator.language || (navigator.languages && navigator.languages[0]);
  if (typeof code !== 'string') return null;
  const two = code.slice(0, 2).toLowerCase();
  return SUPPORTED_LOCALES.includes(two) ? two : null;
}

export function getActiveLocale() {
  if (typeof window !== 'undefined') {
    try {
      const stored = window.localStorage.getItem(LOCALE_KEY);
      if (SUPPORTED_LOCALES.includes(stored)) return stored;
    } catch { /* private mode / quota — fall through */ }
  }
  // v0.62.501 — prefer the DEVICE locale (navigator.language) over the
  // Telegram APP locale (language_code). language_code reflects the Telegram
  // client UI language, a weak signal for the user's real language; a French
  // phone running an English Telegram was resolving to 'en'. detectFromNavigator
  // returns null when the device locale is unsupported, so we still fall back to
  // the Telegram hint, then 'en'.
  return detectFromNavigator() || detectFromTelegram() || 'en';
}

export function setActiveLocale(lang) {
  if (!SUPPORTED_LOCALES.includes(lang)) return;
  if (typeof window === 'undefined') return;
  try { window.localStorage.setItem(LOCALE_KEY, lang); } catch { /* noop */ }
  window.dispatchEvent(new CustomEvent(LOCALE_EVENT, { detail: { lang } }));
  // v0.59.0: best-effort POST to /api/cuisine/user-language so chat
  // replies (deliverPicks, free-text, /hidden) follow the same
  // preference. Lazy-import to avoid a circular dep at module init.
  import('./api.js').then((m) => m.setUserLanguageRemote?.(lang)).catch(() => {});
}

// v0.59.0: track whether we've hydrated from the server's per-user
// preference. Module-level latch so multiple useLocale() calls in
// different components don't each fire a redundant fetch.
let serverHydrated = false;

// ── v0.62.831 — O-345 (b): "settled", which is NOT the same as "started" ────────
//
// THE BUG. `useLocale()` reads localStorage synchronously; this function runs in a
// useEffect. So the first paint shows whatever locale THAT DEVICE last stored, and the
// server's real preference lands one async hop later. The operator saw the Cuisine
// loading overlay in Indonesian under Japanese chrome — one device, two truths, a few
// hundred milliseconds apart.
//
// AND v0.62.825 IS WHY IT BECAME VISIBLE. Before it, POST /api/cuisine/user-language
// rejected `ja` with a 400, so the server could never HOLD ja — there was nothing for
// hydration to correct to. The flash existed and could not be seen. Fixing the
// persistence made the mismatch real, which is worth saying plainly.
//
// `serverHydrated` above cannot answer "has it settled?": it is set to true BEFORE the
// await, precisely so a second caller does not re-fetch. Reusing it would report settled
// while the request is still in flight — the exact wrong answer, from a flag one line
// away from the right one.
const LOCALE_HYDRATED_EVENT = 'gia:locale-hydrated';
let localeSettled = false;
// A ceiling, because the failure mode of gating UI on a promise is UI that never renders.
// Offline, a 401, a hung proxy: the `finally` covers the first two and this covers the
// third. 1500 ms is long enough for a normal round trip and short enough that a wordless
// card is never what a reader is left looking at.
const HYDRATE_CEILING_MS = 1500;
function markLocaleSettled() {
  if (localeSettled) return;
  localeSettled = true;
  try { window.dispatchEvent(new CustomEvent(LOCALE_HYDRATED_EVENT)); } catch { /* noop */ }
}
export function localeIsSettled() { return localeSettled; }

// v0.62.834 — the ceiling has to STOP the race, not just start the clock. Codex, P2 on
// #1783: "when /api/cuisine/user-language takes longer than 1.5 s but eventually succeeds,
// this timer marks the locale ready and exposes the locally stored language while the
// request is still pending … lines 2085-2086 subsequently replace that language and
// recreate the exact wrong-language flash this gate is intended to prevent."
//
// Correct, and confirmed against the source: nothing cancelled or ignored the late
// response, so the ceiling did not remove the flash — it MOVED it, from the first paint to
// roughly a second and a half in, where it is more startling rather than less. A guard whose
// failure mode is the thing it guards against.
//
// SO: a response that arrives after the ceiling is STORED but NOT DISPATCHED. The session
// runs on the locale this device last held — which the reader themselves chose here — and
// the next launch opens in the server's, from a fetch that will usually be warm. The
// alternative, applying it late, keeps a promise about correctness by breaking the one this
// gate was built to make. Deciding which promise wins is the whole point of the item.
let hydrateCeilingFired = false;
// Exported for the test seam only — nothing else imports it; useLocale() calls it from its
// own effect. A grep can assert that `if (!hydrateCeilingFired)` exists; only running the
// function can assert it is checked at the right MOMENT, which is the whole finding.
export async function hydrateFromServerOnce() {
  if (serverHydrated) return;
  serverHydrated = true;
  setTimeout(() => { hydrateCeilingFired = true; markLocaleSettled(); }, HYDRATE_CEILING_MS);
  try {
    const m = await import('./api.js');
    const remote = await m.fetchUserLanguage?.();
    if (SUPPORTED_LOCALES.includes(remote)) {
      // Quietly write to localStorage. Skip the POST that setActiveLocale would
      // otherwise make (the value just came FROM the server — round-tripping is
      // wasteful). Stored either way, on time or late: a late answer is still the
      // right answer for the NEXT launch, and storing it is what makes the next
      // launch open in the server's locale without waiting on the network at all.
      try { window.localStorage.setItem(LOCALE_KEY, remote); } catch { /* noop */ }
      // Dispatch only if we are still inside the window we promised to wait.
      if (!hydrateCeilingFired) {
        window.dispatchEvent(new CustomEvent(LOCALE_EVENT, { detail: { lang: remote } }));
      }
    }
  } catch { /* offline / 401 / 404 — keep local fallback */ }
  finally { markLocaleSettled(); }
}

/**
 * True once the server's stored locale has been applied, or once we have stopped
 * waiting for it. Components that paint BEFORE any interaction — the loading overlay —
 * withhold their words until this is true, so a reader never sees the previous
 * device locale's sentence. Repeat mounts return true synchronously: the latch is
 * module-level, so there is no blank frame after the first load of a session.
 */
export function useLocaleHydrated() {
  const [settled, setSettled] = useState(() => localeSettled);
  useEffect(() => {
    if (localeSettled) { setSettled(true); return undefined; }
    const on = () => setSettled(true);
    window.addEventListener(LOCALE_HYDRATED_EVENT, on);
    return () => window.removeEventListener(LOCALE_HYDRATED_EVENT, on);
  }, []);
  return settled;
}

// React hook: returns [lang, setLang]. Re-renders on locale change
// (own setActiveLocale call OR another tab — storage + custom event).
// On first mount, hydrates from the server's stored preference so the
// TMA matches whatever the user last set via /language in chat.
// v0.62.668 — keep the document's language metadata in sync with the active
// locale. index.html ships a static lang="en"; without this, screen readers
// keep English phonetics (and the browser keeps English hyphenation/font
// rules) after the user switches locale. A module-level listener covers every
// path that changes the locale: setActiveLocale's CustomEvent, the server
// -hydration event, and the cross-tab storage event.
function syncDocumentLang(lang) {
  try { document.documentElement.lang = lang; } catch { /* non-DOM (tests) */ }
}
if (typeof window !== 'undefined') {
  syncDocumentLang(getActiveLocale());
  window.addEventListener(LOCALE_EVENT, (e) => syncDocumentLang(e?.detail?.lang || getActiveLocale()));
  window.addEventListener('storage', (e) => { if (e.key === LOCALE_KEY) syncDocumentLang(getActiveLocale()); });
}

export function useLocale() {
  const [lang, setLangState] = useState(() => getActiveLocale());
  useEffect(() => {
    function onLocale(e) {
      const next = e?.detail?.lang || getActiveLocale();
      setLangState(next);
    }
    function onStorage(e) {
      if (e.key === LOCALE_KEY) setLangState(getActiveLocale());
    }
    window.addEventListener(LOCALE_EVENT, onLocale);
    window.addEventListener('storage', onStorage);
    hydrateFromServerOnce();
    return () => {
      window.removeEventListener(LOCALE_EVENT, onLocale);
      window.removeEventListener('storage', onStorage);
    };
  }, []);
  return [lang, (next) => { setActiveLocale(next); setLangState(next); }];
}
