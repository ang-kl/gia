#!/usr/bin/env node
// scripts/durian-variance-summary.js — v0.61.259
//
// Reads the latest variance JSON outputs and emits a single
// Markdown table summary to doc/durian-variance-summary.md.
//
// Inputs (committed by the .github/workflows/durian-variance.yml
// workflow):
//   data/durian-variance/durian-latest.json
//   data/durian-variance/durian-pastry-latest.json
//
// Output:
//   doc/durian-variance-summary.md  — human-readable Markdown
//                                     with per-mode rollup,
//                                     per-region precision,
//                                     and a long per-query table.

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');
const MODES = [
  { mode: 'durian',         file: 'data/durian-variance/durian-latest.json' },
  { mode: 'durian-pastry',  file: 'data/durian-variance/durian-pastry-latest.json' }
];
const OUT_PATH = path.join(REPO_ROOT, 'doc/durian-variance-summary.md');

function loadReport(relPath) {
  const fullPath = path.join(REPO_ROOT, relPath);
  if (!fs.existsSync(fullPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(fullPath, 'utf8'));
  } catch (err) {
    console.warn(`[summary] failed to parse ${relPath}: ${err.message}`);
    return null;
  }
}

function pctOrDash(x) {
  if (x === null || x === undefined || Number.isNaN(x)) return '—';
  return (x * 100).toFixed(1) + '%';
}

function renderRollupTable(reports) {
  const rows = [];
  rows.push('| Mode | Region | Places | Kept | Rejected | Precision |');
  rows.push('|---|---|---:|---:|---:|---:|');
  for (const { report } of reports) {
    if (!report) continue;
    for (const r of report.regions || []) {
      const t = r.totals || {};
      rows.push(`| ${report.mode} | ${r.name} | ${t.placesReturned ?? '—'} | ${t.kept ?? '—'} | ${t.rejected ?? '—'} | ${pctOrDash(t.precision)} |`);
    }
    const t = report.totals || {};
    rows.push(`| **${report.mode}** | **ALL** | **${t.placesReturned ?? '—'}** | **${t.kept ?? '—'}** | **${t.rejected ?? '—'}** | **${pctOrDash(t.precision)}** |`);
  }
  return rows.join('\n');
}

function renderTypeFreqTable(report) {
  if (!report) return '';
  const merged = {};
  for (const r of report.regions || []) {
    for (const [pt, n] of Object.entries(r.primaryTypeFrequency || {})) {
      merged[pt] = (merged[pt] || 0) + n;
    }
  }
  const sorted = Object.entries(merged).sort((a, b) => b[1] - a[1]);
  const rows = [];
  rows.push(`| primaryType | total returned (${report.mode}) |`);
  rows.push('|---|---:|');
  for (const [pt, n] of sorted.slice(0, 30)) {
    rows.push(`| \`${pt}\` | ${n} |`);
  }
  return rows.join('\n');
}

function renderPerQueryTable(report) {
  if (!report) return '';
  const rows = [];
  rows.push(`### ${report.mode} — per-query precision`);
  rows.push('');
  rows.push('| Region | Lang | Query | Places | Kept | Rejected | Precision |');
  rows.push('|---|---|---|---:|---:|---:|---:|');
  for (const r of report.regions || []) {
    for (const q of r.queries || []) {
      rows.push(`| ${r.name} | ${q.lang} | \`${q.query}\` | ${q.placesReturned} | ${q.keptCount} | ${q.rejectedCount} | ${pctOrDash(q.precision)} |`);
    }
  }
  return rows.join('\n');
}

const reports = MODES.map(({ mode, file }) => ({ mode, report: loadReport(file) }));

const lines = [];
lines.push('# Durian Variance Summary');
lines.push('');
lines.push('Auto-generated by `.github/workflows/durian-variance.yml` after every merge to `main`.');
lines.push('Source data: `data/durian-variance/durian-latest.json` + `data/durian-variance/durian-pastry-latest.json`.');
lines.push('');

const meta = reports.find((x) => x.report)?.report;
if (meta) {
  lines.push(`- **Last run:** ${meta.ranAtIso || '—'}`);
  lines.push(`- **Script version:** \`${meta.scriptVersion || '—'}\``);
  lines.push(`- **Regions covered:** ${(reports[0]?.report?.regions || []).map((r) => r.name).join(' · ') || '—'}`);
  lines.push('');
}

lines.push('## Cross-region rollup');
lines.push('');
lines.push(renderRollupTable(reports));
lines.push('');

for (const { mode, report } of reports) {
  if (!report) {
    lines.push(`## ${mode}`);
    lines.push('');
    lines.push(`_(no JSON file present for \`${mode}\` — workflow likely failed mid-run)_`);
    lines.push('');
    continue;
  }
  lines.push(`## ${mode} — primaryType frequency (top 30)`);
  lines.push('');
  lines.push(renderTypeFreqTable(report));
  lines.push('');
  lines.push('');
  lines.push(renderPerQueryTable(report));
  lines.push('');
}

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, lines.join('\n'));
console.log(`[durian-variance-summary] wrote ${OUT_PATH} (${lines.length} lines)`);
