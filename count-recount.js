// count-recount.js — v0.61.164
//
// Per-item recount functions for the `/ver Periodical` owner
// sub-menu. Each function counts its data source, records the
// result via `count-history.recordCount`, and returns
// `{ item, n, source, ts }` (the new entry) or `null` on failure.
//
// All 14 items the operator listed for v0.61.164. Each function is
// defensively wrapped so a missing module or unreachable API never
// throws; failures record `n=null, source='unavailable'` so the
// history surfaces the gap.
//
// Re-count strategies:
//   - Curated arrays / JSON files: read the file, count the
//     entries (or trust `_meta.featureCount` when present).
//   - LTA-fetched (carparks, bus-stops): call the existing
//     module's fetcher.
//
// A `runAll(redis, opts)` orchestrator runs every item in parallel.
// The v0.61.165 chat UI binds individual recount fns to its
// `Re-check` buttons; the v0.61.166 cron scheduler calls runAll on
// the per-item cadence.

'use strict';

const fs = require('fs');
const path = require('path');

const { recordCount } = require('./count-history');

// Helper — count records in a `data/geo-*.json` overlay file.
// These files were generated by `scripts/build-geo-overlays.js`
// from the data.gov.sg geojson originals. Each carries a
// `_meta.featureCount` field; we prefer that, then fall back to
// `features.length`. Returns null when the file is missing or
// unparseable.
function _countGeoOverlay(relPath) {
  try {
    const abs = path.join(__dirname, relPath);
    const raw = fs.readFileSync(abs, 'utf8');
    const j = JSON.parse(raw);
    if (j && j._meta && Number.isFinite(j._meta.featureCount)) {
      return j._meta.featureCount;
    }
    if (j && Array.isArray(j.features)) return j.features.length;
    return null;
  } catch {
    return null;
  }
}

// Helper — count entries in a plain JSON array file under data/.
function _countJsonArray(relPath, arrayKey = null) {
  try {
    const abs = path.join(__dirname, relPath);
    const raw = fs.readFileSync(abs, 'utf8');
    const j = JSON.parse(raw);
    if (arrayKey && j && Array.isArray(j[arrayKey])) return j[arrayKey].length;
    if (Array.isArray(j)) return j.length;
    if (j && Array.isArray(j.features)) return j.features.length;
    if (j && Array.isArray(j.centres)) return j.centres.length;
    return null;
  } catch {
    return null;
  }
}

// ---- Per-item recount fns -----------------------------------------

async function recountCuisines(redis, opts = {}) {
  let n = null;
  try {
    const cv = require('./cuisines-vault');
    const list = cv.getAllCuisines();
    if (Array.isArray(list)) n = list.length;
  } catch { /* module-missing → n stays null */ }
  const source = n == null ? 'unavailable' : (opts.source || 'manual');
  await recordCount(redis, 'cuisines', n ?? 0, source, opts.notes || '');
  return { item: 'cuisines', n, source };
}

