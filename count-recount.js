async function recountBusStops(redis, opts = {}) {
  // LTA bus stops live in Redis after the first transport.refreshStops
  // call (ZSET `lta:busstops:geo`, ~5500 members). When Redis isn't
  // open OR the cache hasn't warmed yet, fall back to the curated
  // `geoloc/LTABusStop.geojson` count via the json-array helper.
  let n = null;
  if (redis && redis.isOpen) {
    try {
      n = await redis.zCard('lta:busstops:geo');
      if (!Number.isFinite(n) || n <= 0) n = null;
    } catch { n = null; }
  }
  if (n == null) {
    // Curated geojson (operator-curated baseline).
    try {
      const abs = path.join(__dirname, 'geoloc', 'LTABusStop.geojson');
      const raw = fs.readFileSync(abs, 'utf8');
      const j = JSON.parse(raw);
      if (j && Array.isArray(j.features)) n = j.features.length;
    } catch { /* */ }
  }
  const source = n == null ? 'unavailable' : (opts.source || 'manual');
  await recordCount(redis, 'bus-stops', n ?? 0, source, opts.notes || '');
  return { item: 'bus-stops', n, source };
}

