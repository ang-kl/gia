// ---- Dispatch table + runAll --------------------------------------

const RECOUNTERS = Object.freeze({
  'cuisines':            recountCuisines,
  'michelin':            recountMichelin,
  'hawker':              recountHawker,
  'healthier-eateries':  recountHealthierEateries,
  'buildings':           recountBuildings,
  'bus-stops':           recountBusStops,
  'train-stations':      recountTrainStations,
  'train-lines':         recountTrainLines,
  'carparks':            recountCarparks,
  'parks':               recountParks,
  'attractions':         recountAttractions,
  'clinics':             recountClinics,
  'hospitals':           recountHospitals,
  'police':              recountPolice
});

// Single-item dispatch. Returns `null` for unknown item ids.
async function recountOne(redis, item, opts = {}) {
  const fn = RECOUNTERS[item];
  if (typeof fn !== 'function') return null;
  return fn(redis, opts);
}

// Parallel recount of all 14 items. Returns
// `[{item, n, source}, ...]` in the order RECOUNTERS keys are
// enumerated. Per-item failures are isolated (each fn already
// records `source='unavailable'` and returns null-n on error).
async function recountAll(redis, opts = {}) {
  const items = Object.keys(RECOUNTERS);
  return Promise.all(items.map((it) => RECOUNTERS[it](redis, opts)));
}

