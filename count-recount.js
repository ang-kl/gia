async function recountHawker(redis, opts = {}) {
  // Hawker vault parses the curated MD; count the data/hawker-centres.json
  // generated artefact for the live number. Falls back to the vault
  // module's parse if the file is missing.
  let n = _countJsonArray('data/hawker-centres.json');
  if (n == null) {
    try {
      const hv = require('./hawker-vault');
      if (typeof hv.getAll === 'function') n = hv.getAll().length;
      else if (Array.isArray(hv.CENTRES)) n = hv.CENTRES.length;
    } catch { /* */ }
  }
  const source = n == null ? 'unavailable' : (opts.source || 'manual');
  await recordCount(redis, 'hawker', n ?? 0, source, opts.notes || '');
  return { item: 'hawker', n, source };
}

